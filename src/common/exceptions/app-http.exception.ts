import { HttpException, HttpStatus } from '@nestjs/common';

export const APP_ERROR_CODES = {
  INVALID_CREDENTIALS: 'ERR_INVALID_CREDENTIALS',
  AUTHENTICATION_REQUIRED: 'ERR_AUTHENTICATION_REQUIRED',
  ACCESS_TOKEN_EXPIRED: 'ERR_ACCESS_TOKEN_EXPIRED',
  INVALID_REFRESH_SESSION: 'ERR_INVALID_REFRESH_SESSION',
  SUBSCRIPTION_INACTIVE: 'ERR_SUBSCRIPTION_INACTIVE',
  INVALID_CURRENT_PASSWORD: 'ERR_INVALID_CURRENT_PASSWORD',
  CUSTOMER_AGREEMENTS_NOT_ACCEPTED: 'CUSTOMER_AGREEMENTS_NOT_ACCEPTED',
  CUSTOMER_TENANT_AGREEMENTS_NOT_ACCEPTED:
    'CUSTOMER_TENANT_AGREEMENTS_NOT_ACCEPTED',
  CUSTOMER_IDENTITY_NOT_VERIFIED: 'CUSTOMER_IDENTITY_NOT_VERIFIED',
  STAFF_AGREEMENTS_NOT_ACCEPTED: 'STAFF_AGREEMENTS_NOT_ACCEPTED',
  STAFF_IDENTITY_NOT_VERIFIED: 'STAFF_IDENTITY_NOT_VERIFIED',
  TENANT_NOT_READY_FOR_LOAN_APPLICATIONS:
    'TENANT_NOT_READY_FOR_LOAN_APPLICATIONS',
  LOAN_DATASET_EMPTY: 'LOAN_DATASET_EMPTY',
} as const;

export type AppErrorCode =
  (typeof APP_ERROR_CODES)[keyof typeof APP_ERROR_CODES];

export interface AppHttpExceptionBody {
  message: string;
  errorCode: AppErrorCode | string;
}

export function appHttpException(
  status: HttpStatus,
  message: string,
  errorCode: AppErrorCode | string,
  extras?: Record<string, unknown>,
): HttpException {
  return new HttpException(
    { message, errorCode, ...extras },
    status,
  );
}
